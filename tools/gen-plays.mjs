// Writes the generated play scripts in tests/native/ from the fixed content
// (js/levels.js): each round is solved by typing its target words (letter
// keys, then Enter), as a keyboard player would. Run after content changes.
import { writeFileSync } from 'node:fs';
import { FIXED } from '../js/levels.js';

const keys = (w) => [...w].map((c) => `key Key${c.toUpperCase()} 1\nframes 3`).join('\n');
const solve = (level) => level.targets.map((w) => `${keys(w)}\nkey Enter 1\nframes 20`).join('\n');
const out = (name, text) => writeFileSync(new URL(`../tests/native/${name}`, import.meta.url), text + '\n');

// Journey stage 1 by keyboard at a desktop window, a bonus word, a hint, results, Stage 2 started.
const j0 = FIXED['journey-0'];
out('journey.play', `# Generated by tools/gen-plays.mjs. Journey stage 1 at a desktop window:
# a wrong word, a bonus word, a hint, every grid word typed with Enter, the
# results with stars and the breakdown, Next starts stage 2.
# viewport 1280x800@1
until 600 Word
frames 30
save wg-title
click Journey. Seedling
until 300 Seedling Grove
frames 10
save wg-journey
click =Stage 1
until 600 STAGE 1
frames 60
${keys('nfk')}
key Enter 1
until 120 Not in the grove
frames 10
key KeyH 1
until 120 Hint: revealed
frames 10
${keys('fin')}
key Enter 1
until 120 Bonus word
frames 10
save wg-game
${solve(j0)}
until 600 Total
frames 60
save wg-results
expect Stage 2
click =Stage 2
until 600 STAGE 2
frames 30
save wg-stage2`);

// The lesson on a phone by touch: each lesson step's action.
const tu = FIXED['tutorial'];
out('learn-phone.play', `# Generated by tools/gen-plays.mjs. The lesson (Learn) on a portrait phone:
# Next, letters spelled by touch on the wheel's named letters, a word planted,
# a wrong word, Shuffle, Hint, the closing step, then the rest of the grove
# typed; the results.
# viewport 390x844@3
until 600 Word
frames 30
touch Learn & play
until 600 Welcome to the Grove
frames 30
save wg-learn-phone
touch =Next
until 120 Connect letters
frames 10
${[...tu.targets[0]].map((c) => `touch Letter ${c.toUpperCase()}\nframes 6`).join('\n')}
frames 10
touch Submit word
until 120 Try a word
frames 10
${keys('ldi')}
key Enter 1
until 120 Shuffling only
frames 10
touch Shuffle
until 120 Stuck?
frames 30
touch Hint
until 120 Off you go
frames 10
save wg-learn-phone-2
touch =Play!
frames 10
${solve({ targets: tu.targets.slice(1) })}
until 600 Total
frames 60
save wg-learn-results`);
console.log('wrote journey.play, learn-phone.play');
